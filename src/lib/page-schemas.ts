export function getBreadcrumbs(path: string, pageName: string) {
  const parts = path.split("/").filter(Boolean);
  const breadcrumbs = [{ name: "Home", url: "/" }];

  if (parts[0] === "blog") {
    breadcrumbs.push({ name: "Blog", url: "/blog" });
  } else if (parts[0] === "resources") {
    breadcrumbs.push({ name: "Resources", url: "/resources" });
  } else if (parts[0] === "services") {
    breadcrumbs.push({ name: "Services", url: "/services/agency-ad-accounts" });
    const agencyPlatforms = new Set([
      "facebook-agency-ad-account",
      "google-ads-agency-account",
      "tiktok-agency-account",
      "bing-agency-accounts",
      "taboola-agency-ad-accounts",
      "outbrain-agency-ad-accounts",
    ]);
    if (parts[1] && agencyPlatforms.has(parts[1])) {
      breadcrumbs.push({ name: "Agency Ad Accounts", url: "/services/agency-ad-accounts" });
    }
  } else if (parts[0] === "products") {
    breadcrumbs.push({ name: "Products", url: "/resources#meta-assets" });
  } else if (parts[0] === "facebook-unban-services") {
    breadcrumbs.push({ name: "Services", url: "/services/agency-ad-accounts" });
    breadcrumbs.push({
      name: "Account Restrictions",
      url: "/resources#meta-health-recovery",
    });
  }

  const last = breadcrumbs[breadcrumbs.length - 1];
  if (last.url !== path) {
    breadcrumbs.push({ name: pageName, url: path });
  } else {
    last.name = pageName;
  }

  return breadcrumbs;
}
